    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
    
     String nombre  = txtNombreCliente.getText().trim();
    String destino = cboDestino.getSelectedItem().toString();

    if (nombre.isEmpty()) {
        JOptionPane.showMessageDialog(this, "ERROR: Ingrese el nombre del cliente.");
        return;
    }

    int boletos;
    try {
        boletos = Integer.parseInt(txtCantidadBoletos.getText().trim());
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "ERROR: Los boletos deben ser un número entero.");
        return;
    }
    if (boletos <= 0) {
        JOptionPane.showMessageDialog(this, "ERROR: Los boletos deben ser mayor a 0.");
        return;
    }

    String fechaViajeTexto  = FechaCompra.getText().trim();
    String fechaCompraTexto = txtFechaCompra.getText().trim();

    if (!fechaViajeTexto.matches("\\d{2}/\\d{2}/\\d{4}")) {
        JOptionPane.showMessageDialog(this, "ERROR: Use el formato dd/MM/yyyy en la fecha de viaje.");
        return;
    }
    if (!fechaCompraTexto.matches("\\d{2}/\\d{2}/\\d{4}")) {
        JOptionPane.showMessageDialog(this, "ERROR: Use el formato dd/MM/yyyy en la fecha de compra.");
        return;
    }

    Vuelo vuelo = new Vuelo();
    vuelo.setNombreCliente(nombre);
    vuelo.setDestino(destino);
    vuelo.setCatidadBoletos(boletos);
    vuelo.setFechaViaje(fechaViajeTexto);
    vuelo.setFechaCompra(fechaCompraTexto);

    service.agregar(vuelo);
    JOptionPane.showMessageDialog(this, "Vuelo agregado correctamente.");
        
    }//GEN-LAST:event_btnAgregarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
         int fila = tblVuelos.getSelectedRow();

    if (fila == -1) {
        JOptionPane.showMessageDialog(this, "ERROR: Seleccione un vuelo de la tabla.");
        return;
    }

    service.eliminar(fila);
    mdlVuelo.setRowCount(0);

    for (Vuelo v : service.listar()) {
        Object[] f = {
            v.getNombreCliente(),
            v.getDestino(),
            v.getCatidadBoletos(),
            v.getFechaViaje(),
            v.getFechaCompra(),
            v.getCosto(),
            v.getIncremento(),
            v.getDescuento(),
            v.getTotalPagar()
        };
        mdlVuelo.addRow(f);
    }

    JOptionPane.showMessageDialog(this, "Vuelo eliminado correctamente."); 
    }//GEN-LAST:event_btnEliminarActionPerformed
//Terminado
